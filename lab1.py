nameoper = input()
if nameoper == "+":
    cifra = int(input())
    cifradva = int(input())
    itog = cifra + cifradva
if nameoper == "*":
    cifra = int(input())
    cifradva = int(input())
    itog = cifra * cifradva
if nameoper == "-":
    cifra = int(input())
    cifradva = int(input())
    itog = cifra - cifradva
if nameoper == "/":
    cifra = int(input())
    cifradva = int(input())
    itog = cifra / cifradva
print(itog)